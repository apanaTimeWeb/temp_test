const G15 = (1 << 10) | (1 << 8) | (1 << 5) | (1 << 4) | (1 << 2) | (1 << 1) | (1 << 0);
const G15_MASK = (1 << 14) | (1 << 12) | (1 << 10) | (1 << 4) | (1 << 1);

function getBCHDigit(data: number): number {
  let digit = 0;
  let value = data;
  while (value !== 0) {
    digit++;
    value >>>= 1;
  }
  return digit;
}

export function getBCHTypeInfo(data: number): number {
  let d = data << 10;
  while (getBCHDigit(d) - getBCHDigit(G15) >= 0) {
    d ^= G15 << (getBCHDigit(d) - getBCHDigit(G15));
  }
  return ((data << 10) | d) ^ G15_MASK;
}

export function getRSBlocks(typeNumber: number, errorCorrectLevel: number): QRRSBlock[] {
  const rsBlock = RS_BLOCK_TABLE[typeNumber - 1][errorCorrectLevel];
  if (!rsBlock) throw new Error(`bad rs block @ typeNumber:${typeNumber}/errorCorrectLevel:${errorCorrectLevel}`);
  const list: QRRSBlock[] = [];
  for (let i = 0; i < rsBlock.length; i += 3) {
    for (let j = 0; j < rsBlock[i]; j++) {
      list.push(new QRRSBlock(rsBlock[i + 1], rsBlock[i + 2]));
    }
  }
  return list;
}
