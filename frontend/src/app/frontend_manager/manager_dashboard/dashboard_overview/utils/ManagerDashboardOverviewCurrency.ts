/** Formats Indian Rupee currency amounts safely for Manager Dashboard Overview widgets. */
export function formatManagerDashboardOverviewCurrency(amount: number): string {
  const safeAmount = Number.isFinite(amount) ? amount : 0;
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(safeAmount);
}
