import type { FinancialReportExportSpec } from '@/app/frontend_admin/admin_accounts_assets/accounts_financial_reports/utils/AdminAccountsFinancialReportsExportTypes';

export function escapePdfString(str: unknown): string {
  return String(str ?? '')
    .replaceAll('\\', '\\\\')
    .replaceAll('(', '\\(')
    .replaceAll(')', '\\)');
}

export function buildFinancialReportPdfStream(spec: FinancialReportExportSpec): string {
  const [r, g, b] = [0.05, 0.45, 0.35];
  const netProfitMinor = spec.totalIncomeMinor - spec.totalExpenseMinor;
  const marginPct = spec.totalIncomeMinor > 0 ? ((netProfitMinor / spec.totalIncomeMinor) * 100).toFixed(1) : '0.0';

  let stream = `${r} ${g} ${b} rg\n50 760 495 55 re f\n`;
  stream += `1 1 1 rg\nBT\n/F1 14 Tf\n65 792 Td\n(SMART LIBRARY FINANCIAL STATEMENT & AUDIT) Tj\nET\n`;
  stream += `BT\n/F2 9 Tf\n65 774 Td\n(Executive Profit & Loss Ledger | Reporting Horizon: ${escapePdfString(spec.period.toUpperCase())}) Tj\nET\n`;

  stream += '0.1 0.1 0.1 rg\n';
  let y = 730;
  stream += `BT\n/F1 9 Tf\n50 ${y} Td\n(Reporting Horizon:) Tj\nET\nBT\n/F2 9 Tf\n170 ${y} Td\n(${escapePdfString(spec.period)}) Tj\nET\n`;
  y -= 14;

  if (spec.customStartDate || spec.customEndDate) {
    stream += `BT\n/F1 9 Tf\n50 ${y} Td\n(Custom Date Horizon:) Tj\nET\nBT\n/F2 9 Tf\n170 ${y} Td\n(${escapePdfString(spec.customStartDate ?? 'Start')} to ${escapePdfString(spec.customEndDate ?? 'End')}) Tj\nET\n`;
    y -= 14;
  }

  stream += `BT\n/F1 9 Tf\n50 ${y} Td\n(Generated Timestamp:) Tj\nET\nBT\n/F2 9 Tf\n170 ${y} Td\n(${new Date().toLocaleString('en-IN')}) Tj\nET\n`;
  y -= 14;
  stream += `BT\n/F1 9 Tf\n50 ${y} Td\n(Ledger Verification:) Tj\nET\nBT\n/F2 9 Tf\n170 ${y} Td\n(Audited & Reconciled - Library Accounts Cloud) Tj\nET\n`;
  y -= 8;
  stream += `0.8 0.82 0.85 RG\n50 ${y} m 545 ${y} l S\n`;

  y -= 26;
  stream += `0.95 0.97 0.96 rg\n50 ${y - 6} 495 26 re f\n${r} ${g} ${b} RG\n50 ${y - 6} 495 26 re S\n`;
  stream += `0.1 0.2 0.15 rg\nBT\n/F1 8.5 Tf\n60 ${y} Td\n(Total Revenue: INR ${(spec.totalIncomeMinor / 100).toLocaleString('en-IN')}) Tj\nET\n`;
  stream += `0.6 0.15 0.1 rg\nBT\n/F1 8.5 Tf\n230 ${y} Td\n(Expenses: INR ${(spec.totalExpenseMinor / 100).toLocaleString('en-IN')}) Tj\nET\n`;
  stream += `${r} ${g} ${b} rg\nBT\n/F1 9 Tf\n395 ${y} Td\n(Net Profit: INR ${(netProfitMinor / 100).toLocaleString('en-IN')} (${marginPct}%)) Tj\nET\n`;

  y -= 26;
  stream += `0.92 0.94 0.96 rg\n50 ${y - 4} 495 18 re f\n0.1 0.1 0.1 rg\nBT\n/F1 8.5 Tf\n60 ${y} Td\n(PERIOD / MONTH) Tj\nET\nBT\n/F1 8.5 Tf\n200 ${y} Td\n(TOTAL REVENUE) Tj\nET\nBT\n/F1 8.5 Tf\n330 ${y} Td\n(OPERATING EXPENSES) Tj\nET\nBT\n/F1 8.5 Tf\n460 ${y} Td\n(NET MARGIN) Tj\nET\n`;

  y -= 16;
  for (const row of spec.rows) {
    const profit = row.incomeMinor - row.expenseMinor;
    stream += `0.2 0.2 0.2 rg\nBT\n/F2 8.5 Tf\n60 ${y} Td\n(${escapePdfString(row.month)}) Tj\nET\nBT\n/F1 8.5 Tf\n200 ${y} Td\n(INR ${(row.incomeMinor / 100).toLocaleString('en-IN')}) Tj\nET\nBT\n/F1 8.5 Tf\n330 ${y} Td\n(INR ${(row.expenseMinor / 100).toLocaleString('en-IN')}) Tj\nET\nBT\n/F1 8.5 Tf\n460 ${y} Td\n(INR ${(profit / 100).toLocaleString('en-IN')}) Tj\nET\n`;
    y -= 14;
    if (y < 220) break;
  }

  y -= 6;
  stream += `0.85 0.85 0.85 RG\n50 ${y} m 545 ${y} l S\n`;
  y -= 18;
  stream += `0.96 0.94 0.92 rg\n50 ${y - 4} 495 18 re f\n0.2 0.1 0.1 rg\nBT\n/F1 8.5 Tf\n60 ${y} Td\n(EXPENSE CATEGORY) Tj\nET\nBT\n/F1 8.5 Tf\n250 ${y} Td\n(AMOUNT DISBURSED) Tj\nET\nBT\n/F1 8.5 Tf\n440 ${y} Td\n(PORTFOLIO SHARE) Tj\nET\n`;

  y -= 15;
  for (const cat of spec.categories) {
    stream += `0.2 0.2 0.2 rg\nBT\n/F2 8 Tf\n60 ${y} Td\n(${escapePdfString(cat.category)}) Tj\nET\nBT\n/F1 8 Tf\n250 ${y} Td\n(INR ${(cat.amountMinor / 100).toLocaleString('en-IN')}) Tj\nET\nBT\n/F2 8 Tf\n440 ${y} Td\n(${cat.pct}%) Tj\nET\n`;
    y -= 13;
  }

  stream += '0.3 0.3 0.3 RG\n80 85 m 220 85 l S\n0.3 0.3 0.3 RG\n380 85 m 520 85 l S\n';
  stream += '0.2 0.2 0.2 rg\nBT\n/F2 8 Tf\n100 72 Td\n(Prepared By: Chief Accountant) Tj\nET\n0.2 0.2 0.2 rg\nBT\n/F2 8 Tf\n405 72 Td\n(Authorized Executive Signatory) Tj\nET\n';
  stream += `0.5 0.5 0.5 rg\nBT\n/F2 7.5 Tf\n50 50 Td\n(CONFIDENTIAL & PROPRIETARY. Generated by Smart Library Cloud ERP Accounting System.) Tj\nET\n`;
  return stream;
}
